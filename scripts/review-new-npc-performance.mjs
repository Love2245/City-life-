export function reviewNewNpcPerformance(rows) {
  const changes = [], missing = [];
  // 上一稿的三句介绍不再是有效台词，不能继续打包进运行时标注表。
  const obsolete = new Set(['我俩双胞胎，她每次介绍都得把这个纠正一遍。', '你每次都先说。', '范珂汐。师范学院读书。还有，我是姐姐。']);
  for(let i=rows.length-1;i>=0;i--)if(obsolete.has(rows[i].text))rows.splice(i,1);
  for(const [npcId,categories] of Object.entries(reviews))for(const [category,cues] of Object.entries(categories)){
    for(const cue of cues){
      const matched=rows.filter(row=>row.npcId===npcId&&row.text.includes(cue));
      if(!matched.length){missing.push(`${npcId} / ${cue}`);continue;}
      for(const row of matched){
        const previous=row.category;
        row.category=category;row.intensity=category==='neutral'?0:1;
        row.reason='2026-10-16逐段复核：本人当下的语气、表情或讲述态度；回忆与他人情绪不直接重演。';
        if(previous!==category)changes.push({npcId,text:row.text,previous,category});
      }
    }
  }
  if(missing.length)throw new Error(`Missing reviewed paragraphs:\n${missing.join('\n')}`);
  return changes;
}
