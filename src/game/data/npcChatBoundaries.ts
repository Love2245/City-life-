export function npcChatBoundaryLine(
  npcId: string,
  kind: NpcChatBoundaryKind,
  affinity: number,
): string {
  const lines = NPC_CHAT_BOUNDARIES[npcId];
  if (!lines) return "对方委婉表示还有事情要处理，今天先聊到这里。";
  if (affinity >= 70 && (kind === "reminder" || kind === "polite")) {
    return lines.close?.[kind] ?? lines[kind];
  }
  return lines[kind];
}
