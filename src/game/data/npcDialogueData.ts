/** 每个节点额外提供一条中性、贴合人物主题的回应。 */
export function npcConversationExtraChoice(
  npcId: string,
  stageKey: NpcTalkStageKey,
  nodeIndex: number,
): string {
  const topics = NPC_DIALOGUE_TOPICS[npcId];
  const topic = topics?.[nodeIndex] ?? "这件事";
  const template = EXTRA_REPLY_TEMPLATES[stageKey][nodeIndex] ?? "我想先多听一点，再说我的看法。";
  return template.replace("{topic}", topic);
}

