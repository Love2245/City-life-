/**
 * v1.43 NPC 对话内容。
 *
 * 每个关系阶段固定五个节点，每个节点都拥有自己的台词与回答。
 * 台词统一使用“（动作/神态。）直接说话”的形式，方便之后替换立绘、
 * 加入语音或继续扩写分支。选项默认合流到同阶段的下一个节点，
 * 最后一节点的特殊选项承载保留的物品赠送机制。
 */
import type { ConversationEffects } from "../types";
import type { NpcTalkStageKey } from "../core/npcs";

export interface NpcTalkSpecial {
  option: 0 | 1;
  affinity?: number;
  effects?: ConversationEffects;
  log?: string;
}

export interface NpcTalkNodeSeed {
  text: string;
  choices: readonly [string, string];
  affinities?: readonly [number, number];
  special?: NpcTalkSpecial;
}

export interface NpcTalkStageSeed {
  nodes: readonly [
    NpcTalkNodeSeed,
    NpcTalkNodeSeed,
    NpcTalkNodeSeed,
    NpcTalkNodeSeed,
    NpcTalkNodeSeed,
  ];
}

export interface NpcDialogueSeed {
  stages: Record<NpcTalkStageKey, NpcTalkStageSeed>;
}

const node = (
  text: string,
  choices: readonly [string, string],
  affinities: readonly [number, number] = [1, -1],
  special?: NpcTalkSpecial,
): NpcTalkNodeSeed => ({ text, choices, affinities, special });

const stage = (nodes: NpcTalkStageSeed["nodes"]): NpcTalkStageSeed => ({ nodes });

